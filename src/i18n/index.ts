export type Locale = "en" | "ar";
export type Strings = typeof en;

export function useI18n() {
  const locales = useLocales();
  const locale: Locale = locales[0]?.languageCode === "ar" ? "ar" : "en";
  const t = locale === "ar" ? ar : en;
  /** Picks the Arabic field when the device is Arabic and the value exists. */
  const pick = (enValue: string | null | undefined, arValue: string | null | undefined) =>
    (locale === "ar" && arValue ? arValue : enValue) ?? "";
  const price = (n: number) => `${Number.isInteger(n) ? n : n.toFixed(2)} ${t.egp}`;
  return { locale, t, pick, price };
}

export const statusLabel = (t: Strings, s: string) => String(t[`status_${s}` as keyof Strings] ?? s);
